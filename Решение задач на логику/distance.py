"""
Решение:
1) На картинке одна длинная дорога Д-В, к ней сбоку подходят дороги от А, Г и Б, по порядку от Д: А, Г, Б
2) g = длина боковой дороги от Г до длинной дороги, путь от Г до А и до Б идёт сначала по ней
3) (А-Г)+(Г-Б)-(А-Б)=10+11-8=13
4) В сумме А-Г и Г-Б дорога g встречается два раза, остальные участки в сумме и в А-Б одинаковые и сокращаются, поэтому 2*g=13 и g=6.5
5) Д-Г=15, из них боковая дорога g=6.5, значит по длинной дороге от Д до Г 15-6.5=8.5
6) В-Г=17, из них боковая дорога g=6.5, значит по длинной дороге от Г до В 17-6.5=10.5
7) Д-В=8.5+10.5=19
"""

# расстояния из условия (км)
DISTANCE_D_G = 15
DISTANCE_A_G = 10
DISTANCE_G_B = 11
DISTANCE_A_B = 8
DISTANCE_V_G = 17

# длина боковой дороги от Г до главной дороги
side_road = (DISTANCE_A_G + DISTANCE_G_B - DISTANCE_A_B) / 2

# расстояние от дома Джонатана до Вирусологического центра
distance = DISTANCE_D_G + DISTANCE_V_G - 2 * side_road

print(f"Вирусологический центр находится в {distance:.0f}км от дома Джона")