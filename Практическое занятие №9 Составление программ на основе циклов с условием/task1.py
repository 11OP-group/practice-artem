n = int(input(f"\033[32mВведите число: \033[0m"))

i = 1  # счётчик

while i <= n:
    i += 1  # увеличиваем сразу в начале
    if 5 <= i <= 9 or 17 <= i <= 37 or 78 <= i <= 87: # диапозоны запрещенных чисел
        continue
    print(i)

print(f"\033[32mВыше выведены все числа, кроме чисел из запрещённого диапазона\033[0m")